CREATE TABLE products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(120) NOT NULL,
  category varchar(40) NOT NULL,
  description text,
  price numeric(10, 2) NOT NULL CHECK (price > 0),
  stock integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
  available boolean NOT NULL DEFAULT true,
  image text
);

CREATE TABLE customers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name varchar(120) NOT NULL,
  phone varchar(30) NOT NULL UNIQUE,
  email varchar(160) UNIQUE,
  address text
);

CREATE TYPE order_status AS ENUM (
  'NUEVO',
  'CONFIRMADO',
  'EN PREPARACION',
  'LISTO',
  'EN CAMINO',
  'ENTREGADO'
);

CREATE TYPE delivery_type AS ENUM ('RETIRO', 'DOMICILIO');

CREATE TABLE orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
  status order_status NOT NULL DEFAULT 'NUEVO',
  delivery_type delivery_type NOT NULL,
  address text,
  total numeric(12, 2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT home_delivery_requires_address
    CHECK (delivery_type <> 'DOMICILIO' OR address IS NOT NULL)
);

CREATE TABLE order_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id integer NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(10, 2) NOT NULL CHECK (unit_price > 0),
  CONSTRAINT one_product_per_order UNIQUE (order_id, product_id)
);
